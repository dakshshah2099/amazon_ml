        "    s23_ids = pairs_df['cand_entity_id'].values",
        "    for t in thresholds:",
        "        preds = {s1: set() for s1 in gt_mapping.keys()}",
        "        mask = probs >= t",
        "        for s1, cand in zip(s1_ids[mask], s23_ids[mask]):",
        "            preds[s1].add(cand)",
        "        f05, p, r = compute_macro_f05(gt_mapping, preds)",
        "        if f05 > best_f05:",
        "            best_f05 = f05",
        "            best_thresh = t",
        "    return best_thresh, best_f05"
